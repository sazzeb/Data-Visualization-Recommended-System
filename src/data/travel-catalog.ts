export function getRecommendationFilterGroups(
  interests: string[]
) {
  const selectedGroups = Object.entries(
    RECOMMENDATION_FILTER_GROUPS
  )
    .filter(([key]) => key !== "Additional Interests")
    .flatMap(([, groups]) => groups)
    .filter(group => interests.includes(group.label));

  return [
    ...selectedGroups,
    ...RECOMMENDATION_FILTER_GROUPS[
      "Additional Interests"
    ],
  ];
}


